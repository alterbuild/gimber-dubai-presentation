def inside(x, y, poly):
    """Even-odd ray casting."""
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def dots():
    """-> (land, belgium, uae): lists of (x, y) in map pixels."""
    land, be, ae = [], [], []
    row_h = PITCH * 0.866
    j = 0
    while (j + 0.5) * row_h < H:
        y = (j + 0.5) * row_h
        i = 0
        while True:
            x = (i + 0.5 + 0.5 * (j % 2)) * PITCH
            if x > W - PITCH / 2:
                break
            lon, lat = lonlat(x, y)
            if inside(lon, lat, BELGIUM):
                be.append((x, y))
            elif inside(lon, lat, UAE):
                ae.append((x, y))
            elif any(inside(lon, lat, p) for p in LAND) and not any(inside(lon, lat, s) for s in SEAS):
                land.append((x, y))
            i += 1
        j += 1
    return land, be, ae


def path(points):
    return ''.join('M%.1f %.1fh0' % p for p in points)


def placeholders():
    """-> {placeholder: SVG path} for build.py (zero-length segments with round caps draw the dots)."""
    land, be, ae = dots()
    line = arc_points()
    tiers = ([], [], [])
    for x, y in land:
        d = min(hypot(x - a, y - b) for a, b in line)
        t = 0 if d <= NEAR else 1 if d <= MID else 2
        if x > W - 22 or y > H - 14:      # the map fades out at its right and bottom edges
            t = 2
        elif x > W - 60 or y > H - 40:
            t = max(t, 1)
        tiers[t].append((x, y))
    return {'ROUTE_NEAR': path(tiers[0]), 'ROUTE_MID': path(tiers[1]), 'ROUTE_FAR': path(tiers[2]),
            'ROUTE_BE': path(be), 'ROUTE_AE': path(ae)}


def great_circle(a, b, n):
    (lo1, la1), (lo2, la2) = [(radians(p[0]), radians(p[1])) for p in (a, b)]
    d = 2 * asin(sqrt(sin((la2 - la1) / 2) ** 2 + cos(la1) * cos(la2) * sin((lo2 - lo1) / 2) ** 2))
    out = []
    for k in range(n + 1):
        f = k / n
        p, q = sin((1 - f) * d) / sin(d), sin(f * d) / sin(d)
        x = p * cos(la1) * cos(lo1) + q * cos(la2) * cos(lo2)
        y = p * cos(la1) * sin(lo1) + q * cos(la2) * sin(lo2)
        z = p * sin(la1) + q * sin(la2)
        out.append((degrees(atan2(y, x)), degrees(atan2(z, sqrt(x * x + y * y)))))
    return out, d * 6371.0088


def arc_points(n=128):
    """The great circle from Halle to Dubai as a list of (x, y) map pixels."""
    return [xy(*p) for p in great_circle(HALLE, DUBAI, n)[0]]


def arc(n=64):
    """-> (SVG path of the great circle from Halle to Dubai in map pixels, distance in km)."""
    pts, km = great_circle(HALLE, DUBAI, n)
    return 'M' + 'L'.join('%.1f %.1f' % xy(*p) for p in pts), km


