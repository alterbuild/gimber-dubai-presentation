def xy(lon, lat):
    return (lon - LON0) * W / (LON1 - LON0), (LAT1 - lat) * H / (LAT1 - LAT0)


def lonlat(x, y):
    return LON0 + x * (LON1 - LON0) / W, LAT1 - y * (LAT1 - LAT0) / H


